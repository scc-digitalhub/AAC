package it.smartcommunitylab.aac.eidas.provider;

import it.smartcommunitylab.aac.SystemKeys;
import it.smartcommunitylab.aac.eidas.model.EIDASAttributeSet;
import it.smartcommunitylab.aac.identity.model.ConfigurableIdentityProvider;
import it.smartcommunitylab.aac.identity.provider.IdentityProviderSettingsMap;
import it.smartcommunitylab.aac.spid.model.SpidAttribute;
import it.smartcommunitylab.aac.spid.model.SpidAttributeConsumingService;
import it.smartcommunitylab.aac.spid.provider.SpidIdentityProviderConfig;
import it.smartcommunitylab.aac.spid.provider.SpidIdentityProviderConfigMap;
import java.util.LinkedHashSet;
import java.util.Set;
import java.util.stream.Collectors;
import org.springframework.util.StringUtils;

/*
 * Configuration of an eIDAS identity provider.
 *
 * The italian eIDAS node is a SPID identity provider, so the SPID configuration is inherited whole:
 * same configMap (signing credentials, organization, contact person, attribute consuming services,
 * authnContext) and same relying party registration logic, including the single upstream node that
 * setIdentityProviders() derives from `idpMetadataUrl`.
 *
 * Our own endpoints live under /auth/eidas/: the SPID configuration builds every url (assertion
 * consumer, single logout, metadata) from its authority, which here is "eidas".
 *
 * The metadata of the node are loaded by the inherited setIdentityProviders(), exactly as SPID loads
 * those of an identity provider declared by url: same path, no additional check. The eidas module
 * keeps the trust model of the SPID module it reuses.
 */
public class EIDASIdentityProviderConfig extends SpidIdentityProviderConfig {

    public static final long serialVersionUID = SystemKeys.AAC_EIDAS_SERIAL_VERSION;

    public static final String RESOURCE_TYPE =
        SystemKeys.RESOURCE_PROVIDER +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.RESOURCE_CONFIG +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.RESOURCE_IDENTITY_PROVIDER +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.AUTHORITY_EIDAS;

    public EIDASIdentityProviderConfig(String provider, String realm) {
        super(SystemKeys.AUTHORITY_EIDAS, provider, realm, new EIDASIdentityProviderConfigMap());
    }

    public EIDASIdentityProviderConfig(
        ConfigurableIdentityProvider cp,
        IdentityProviderSettingsMap settings,
        SpidIdentityProviderConfigMap configs
    ) {
        // authority comes from the configurable provider, ie. "eidas"
        super(cp, settings, configs);

        // an eidas provider does not come to exist on an invalid configuration, whatever the path
        // that builds it (registration, bootstrap, direct getConfig): same rule SPID applies to its
        // signing credentials. Bean Validation reports the same checks earlier, field by field.
        if (configs instanceof EIDASIdentityProviderConfigMap) {
            ((EIDASIdentityProviderConfigMap) configs).assertValid();
        }
        requireAttributeSetsInMetadata();
    }

    /* true when the SP metadata are supplied (metadataUrl / metadataXML) rather than generated by AAC */
    private boolean hasExternalMetadata() {
        return StringUtils.hasText(getConfigMap().getMetadataUrl()) || StringUtils.hasText(getConfigMap().getMetadataXML());
    }

    /*
     * The SP metadata must declare both AttributeConsumingService elements prescribed by AgID (Avviso
     * n. 01-2018, par. 4): index 99 with the minimum set and index 100 with the full set, each with
     * exactly those attributes. With the metadata generated by AAC they are built from EIDASAttributeSet
     * and this holds by construction; with external metadata (metadataUrl / metadataXML) the services
     * are whatever the document declares, so they are checked here, index by index, at registration.
     * SPID already refuses an index missing from the metadata (loadMetadataConfiguration); this adds
     * the other index and the attributes. Only index and attributes are checked, not the ServiceName.
     */
    private void requireAttributeSetsInMetadata() {
        if (!hasExternalMetadata()) {
            return;
        }
        Set<SpidAttributeConsumingService> services = getAttributeConsumingServices();
        for (EIDASAttributeSet set : EIDASAttributeSet.values()) {
            SpidAttributeConsumingService service = services
                .stream()
                .filter(acs -> acs.getIndex() != null && acs.getIndex() == set.getIndex())
                .findFirst()
                .orElse(null);
            if (service == null) {
                throw new IllegalArgumentException(
                    "attribute consuming service " + set.getIndex() + " (" + set.getValue() + " set) not found in metadata"
                );
            }
            Set<SpidAttribute> expected = EIDASIdentityProviderConfigMap.toSpidAttributes(set.getAttributes());
            Set<SpidAttribute> requested = service.getAttributes() != null ? service.getAttributes() : Set.of();
            if (!requested.equals(expected)) {
                throw new IllegalArgumentException(
                    "attribute consuming service " + set.getIndex() + " in metadata must request exactly the " +
                    set.getValue() + " set: " + names(expected) + ", found: " + names(requested)
                );
            }
        }
    }

    private static String names(Set<SpidAttribute> attributes) {
        return attributes.stream().map(SpidAttribute::getValue).sorted().collect(Collectors.joining(", "));
    }

    /*
     * The services the metadata publish and the assertion validator reads. Generated metadata carry the
     * two prescribed services, whatever the chosen set (the choice only selects the index of the
     * AuthnRequest); external metadata carry their own, verified above. This is where the eidas sets
     * are translated for the SPID stack: index, ServiceName and attributes in SPID names.
     */
    @Override
    public Set<SpidAttributeConsumingService> getAttributeConsumingServices() {
        if (hasExternalMetadata()) {
            return super.getAttributeConsumingServices();
        }
        Set<SpidAttributeConsumingService> services = new LinkedHashSet<>();
        for (EIDASAttributeSet set : EIDASAttributeSet.values()) {
            services.add(
                new SpidAttributeConsumingService(
                    set.getIndex(),
                    set.getServiceName(),
                    EIDASIdentityProviderConfigMap.toSpidAttributes(set.getAttributes())
                )
            );
        }
        return services;
    }

    /**
     * Private constructor for JPA and other serialization tools.
     */
    @SuppressWarnings("unused")
    private EIDASIdentityProviderConfig() {
        super(SystemKeys.AUTHORITY_EIDAS, null, null, new EIDASIdentityProviderConfigMap());
    }
}
