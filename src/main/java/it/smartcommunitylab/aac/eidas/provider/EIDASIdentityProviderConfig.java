package it.smartcommunitylab.aac.eidas.provider;

import it.smartcommunitylab.aac.SystemKeys;
import it.smartcommunitylab.aac.eidas.model.EIDASAttribute;
import it.smartcommunitylab.aac.identity.model.ConfigurableIdentityProvider;
import it.smartcommunitylab.aac.identity.provider.IdentityProviderSettingsMap;
import it.smartcommunitylab.aac.eidas.auth.EIDASMetadataSignatureVerifier;
import it.smartcommunitylab.aac.spid.model.SpidAttribute;
import it.smartcommunitylab.aac.spid.model.SpidAttributeConsumingService;
import it.smartcommunitylab.aac.spid.model.SpidRegistration;
import it.smartcommunitylab.aac.spid.provider.SpidIdentityProviderConfig;
import it.smartcommunitylab.aac.spid.provider.SpidIdentityProviderConfigMap;
import java.util.Collection;
import java.util.Set;
import java.util.stream.Collectors;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.util.StringUtils;
import org.springframework.web.client.RestTemplate;

/*
 * Configuration of an eIDAS identity provider.
 *
 * The italian eIDAS node is a SPID identity provider, so the SPID configuration is inherited whole:
 * same configMap (signing credentials, organization, contact person, attribute consuming services,
 * authnContext) and same relying party registration logic, including the single upstream node that
 * setIdentityProviders() derives from `idpMetadataUrl`.
 *
 * Our own endpoints live under /auth/eidas/: the SPID configuration builds every url (assertion
 * consumer, single logout, metadata) from its authority, which here is "eidas".
 *
 * One thing is added: the metadata of the node are verified (signature) before the inherited code
 * loads them, see setIdentityProviders(). For SPID the trust in idp metadata comes from the AgID
 * registry; for a single url it has to be established here.
 */
public class EIDASIdentityProviderConfig extends SpidIdentityProviderConfig {

    public static final long serialVersionUID = SystemKeys.AAC_EIDAS_SERIAL_VERSION;

    public static final String RESOURCE_TYPE =
        SystemKeys.RESOURCE_PROVIDER +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.RESOURCE_CONFIG +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.RESOURCE_IDENTITY_PROVIDER +
        SystemKeys.ID_SEPARATOR +
        SystemKeys.AUTHORITY_EIDAS;

    public EIDASIdentityProviderConfig(String provider, String realm) {
        super(SystemKeys.AUTHORITY_EIDAS, provider, realm, new EIDASIdentityProviderConfigMap());
    }

    public EIDASIdentityProviderConfig(
        ConfigurableIdentityProvider cp,
        IdentityProviderSettingsMap settings,
        SpidIdentityProviderConfigMap configs
    ) {
        // authority comes from the configurable provider, ie. "eidas"
        super(cp, settings, configs);

        // an eidas provider does not come to exist on an invalid configuration, whatever the path
        // that builds it (registration, bootstrap, direct getConfig): same rule SPID applies to its
        // signing credentials. Bean Validation reports the same checks earlier, field by field.
        if (configs instanceof EIDASIdentityProviderConfigMap) {
            ((EIDASIdentityProviderConfigMap) configs).assertValid();
        }
        requireMinimumDataSetInMetadata();
    }

    /*
     * What the node is asked for is the AttributeConsumingService the AuthnRequest points to, not
     * eidasAttributes: with an external SP metadata (metadataUrl / metadataXML) the two can differ,
     * and a service without the Minimum Data Set would make a provider the node cannot serve. SPID
     * already refuses an index missing from the metadata (loadMetadataConfiguration); here the service
     * at that index must also request the four mandatory attributes. With the metadata generated by
     * AAC the service is built from eidasAttributes, already checked, and this passes by construction.
     */
    private void requireMinimumDataSetInMetadata() {
        Integer index = getAttributeConsumingServiceIndex();
        SpidAttributeConsumingService service = getAttributeConsumingServices()
            .stream()
            .filter(acs -> index.equals(acs.getIndex()))
            .findFirst()
            .orElse(null);
        if (service == null) {
            // no attribute consuming service at all (eg. generated metadata without attributes): the
            // AuthnRequest would carry an index the metadata does not declare
            throw new IllegalArgumentException(
                "attribute consuming service " + index + " not found in metadata: an eidas provider must request the minimum data set"
            );
        }

        Set<SpidAttribute> requested = service.getAttributes() != null
            ? service.getAttributes()
            : Set.of();
        Set<SpidAttribute> missing = EIDASAttribute.toSpidAttributes(EIDASAttribute.mandatory());
        missing.removeAll(requested);
        if (!missing.isEmpty()) {
            throw new IllegalArgumentException(
                "attribute consuming service " + index + " in metadata must request the minimum data set, missing: " +
                missing.stream().map(SpidAttribute::getValue).sorted().collect(Collectors.joining(", "))
            );
        }
    }

    /**
     * Private constructor for JPA and other serialization tools.
     */
    @SuppressWarnings("unused")
    private EIDASIdentityProviderConfig() {
        super(SystemKeys.AUTHORITY_EIDAS, null, null, new EIDASIdentityProviderConfigMap());
    }

    private static final Logger logger = LoggerFactory.getLogger(EIDASIdentityProviderConfig.class);

    private transient RestTemplate restTemplate;

    /*
     * The inherited implementation fetches idpMetadataUrl with Spring Security RelyingPartyRegistrations,
     * which reads the certificates and ignores the Signature. The document is fetched once more here and
     * its signature verified first: unsigned or tampered metadata fail the registration of the provider
     * with a clear message, instead of quietly installing a certificate we would then validate Responses
     * against. The double fetch happens at registration only.
     */
    @Override
    public void setIdentityProviders(Collection<SpidRegistration> registrations) {
        SpidIdentityProviderConfigMap map = getConfigMap();
        if (map instanceof EIDASIdentityProviderConfigMap && StringUtils.hasText(map.getIdpMetadataUrl())) {
            EIDASIdentityProviderConfigMap eidasMap = (EIDASIdentityProviderConfigMap) map;
            if (eidasMap.shouldVerifyIdpMetadataSignature()) {
                String metadata = fetchMetadata(map.getIdpMetadataUrl());
                EIDASMetadataSignatureVerifier.verify(metadata, eidasMap.getIdpMetadataSigningCertificate());
            } else {
                logger.warn(
                    "eidas provider {}: signature of the node metadata at {} NOT verified (verifyIdpMetadataSignature=false)",
                    getProvider(),
                    map.getIdpMetadataUrl()
                );
            }
        }

        super.setIdentityProviders(registrations);
    }

    private String fetchMetadata(String url) {
        try {
            return getRestTemplate().getForObject(url, String.class);
        } catch (RuntimeException e) {
            throw new IllegalArgumentException("eIDAS node metadata at " + url + " cannot be fetched: " + e.getMessage(), e);
        }
    }

    private RestTemplate getRestTemplate() {
        if (restTemplate == null) {
            restTemplate = new RestTemplate();
        }
        return restTemplate;
    }
}
